import unreal, math
A=unreal.get_editor_subsystem(unreal.EditorActorSubsystem)
camera=next((a for a in A.get_all_level_actors() if a.get_actor_label()=='CAM_YU7_Beauty'),None)
loc=unreal.Vector(-850,780,265)
rot=unreal.MathLibrary.find_look_at_rotation(loc,unreal.Vector(0,0,80))
if not camera: camera=A.spawn_actor_from_class(unreal.CineCameraActor,loc,rot)
camera.set_actor_location_and_rotation(loc,rot,False,True)
camera.set_actor_label('CAM_YU7_Beauty'); camera.set_folder_path('YU7/Lookdev')
c=camera.get_cine_camera_component()
f=c.filmback; f.sensor_width=36; f.sensor_height=20.25; c.set_editor_property('filmback',f)
c.set_editor_property('current_focal_length',55.); c.set_editor_property('current_aperture',8.)
focus=c.focus_settings; focus.focus_method=unreal.CameraFocusMethod.DISABLE; c.set_editor_property('focus_settings',focus)
level=unreal.get_editor_subsystem(unreal.LevelEditorSubsystem); key=level.get_active_viewport_config_key()
level.set_level_viewport_camera_info(loc,rot,key); level.set_level_viewport_fov(math.degrees(2*math.atan(36/110)),key)
level.editor_set_viewport_realtime(True,key)
A.clear_actor_selection_set()
unreal.AutomationLibrary.set_editor_viewport_view_mode(unreal.ViewModeIndex.VMI_LIT)
unreal.EditorLoadingAndSavingUtils.save_dirty_packages(True,True)
RESULT={'camera':camera.get_actor_label(),'focal_length':55}
